// Function to transform text to a specific font style
function transformToFontStyle(text, styleName) {
    if (!FONT_STYLES[styleName]) {
        return text;
    }
    
    const style = FONT_STYLES[styleName];
    let result = '';
    
    for (let char of text) {
        const upper = char.toUpperCase();
        result += style[upper] || char;
    }
    
    return result;
}

